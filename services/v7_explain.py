"""Gemini explanation for a scored v7 pair. Torch-free so the API process can import it."""

import json
import logging
from typing import Any, Dict, List

from services.reasoning import reasoning_service

logger = logging.getLogger("resync.v7_explain")

STRICT_CORRELATION_PROMPT = """
You are an objective, literal logic auditor. Your task is to explain the correlation between two sections of a research manuscript.
YOUR STRICT RULES:
1. Do NOT assume or mention the research type (never say quantitative, qualitative, etc.).
2. Do NOT demand specific structural changes or missing chapters.
3. Do NOT use outside academic knowledge.
4. Your ONLY job is to check if Section B logically correlates with Section A.
5. Do NOT change the scores provided. They are mathematically generated by our PyTorch model.

--- DATA ---
SECTION A ({role_a}): {text_a}
SECTION B ({role_b}): {text_b}

MODEL SCORES (0.0 to 1.0):
- Overall Coherence: {score_overall}
- Objectives Alignment: {score_obj}
- Methodology Fit: {score_meth}
- Numeric Consistency: {score_num}
- Claim Support: {score_claim}

CULPRIT SENTENCES:
Section A Culprits: {culprits_a}
Section B Culprits: {culprits_b}

--- YOUR TASK ---
Respond STRICTLY in the following JSON format with exactly these 4 keys.
{{
  "coherence_scores": {{ "overall": {score_overall}, "objectives": {score_obj}, "methodology": {score_meth}, "numeric": {score_num}, "claims": {score_claim} }},
  "highlighted_inconsistencies": ["Quote the exact contradiction. If coherent, say 'No major inconsistencies found.'"],
  "recommendations": ["Actionable advice on how to fix it using ONLY the text provided."],
  "reference_list": ["Cite the exact section and specific sentence used for the evaluation."]
}}
"""


def _format_culprits(culprits: List[dict]) -> str:
    if not culprits:
        return "None"
    return "\n".join(f'- "{c["sentence"]}"' for c in culprits)


def _as_str_list(value: Any) -> List[str]:
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, list):
        return []
    return [str(item) for item in value if str(item).strip()]


def coherence_scores(scores: Dict[str, float]) -> Dict[str, float]:
    """The model's numbers, rounded. Always written over whatever Gemini returns."""
    return {
        "overall": round(scores["overall_coherence"], 3),
        "objectives": round(scores["objectives_alignment"], 3),
        "methodology": round(scores["methodology_fit"], 3),
        "numeric": round(scores["numeric_consistency"], 3),
        "claims": round(scores["claim_support"], 3),
    }


def normalize_explanation(raw: Any, scores: Dict[str, float]) -> Dict[str, Any]:
    """Exactly the 4 required keys, with model-generated scores enforced."""
    raw = raw if isinstance(raw, dict) else {}
    return {
        "coherence_scores": coherence_scores(scores),
        "highlighted_inconsistencies": _as_str_list(raw.get("highlighted_inconsistencies")),
        "recommendations": _as_str_list(raw.get("recommendations")),
        "reference_list": _as_str_list(raw.get("reference_list")),
    }


async def explain_pair(role_a: str, text_a: str, role_b: str, text_b: str,
                       scores: Dict[str, float], culprits_a: List[dict], culprits_b: List[dict]) -> Dict[str, Any]:
    shown = coherence_scores(scores)
    prompt = STRICT_CORRELATION_PROMPT.format(
        role_a=role_a, text_a=reasoning_service._truncate_text(text_a),
        role_b=role_b, text_b=reasoning_service._truncate_text(text_b),
        score_overall=shown["overall"], score_obj=shown["objectives"], score_meth=shown["methodology"],
        score_num=shown["numeric"], score_claim=shown["claims"],
        culprits_a=_format_culprits(culprits_a), culprits_b=_format_culprits(culprits_b),
    )
    payload = {
        "contents": [{"role": "user", "parts": [{"text": prompt}]}],
        "generationConfig": {"temperature": 0.2, "responseMimeType": "application/json"},
    }
    try:
        response = await reasoning_service._post_gemini_with_retry(payload)
        response.raise_for_status()
        raw = json.loads(response.json()["candidates"][0]["content"]["parts"][0]["text"])
        return normalize_explanation(raw, scores)
    except Exception:
        logger.exception("v7 Gemini explanation failed for %s -> %s", role_a, role_b)
        fallback = normalize_explanation({}, scores)
        fallback["recommendations"] = ["The AI explanation could not be generated for this pair. The scores above are still valid."]
        return fallback
